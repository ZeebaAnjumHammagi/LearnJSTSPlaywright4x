// Naming Conventions (Cases)
// ============================================
// 1. CamelCase is a naming convention where the first letter of each word is capitalized except for the first word.
var lastName = "Hammagi"; // CamelCase
let userName = "camelCase";
let totalPrice = 99.99;
let isLoggedIn = true;

// 2. PascalCase (UpperCamelCase) is a naming convention where the first letter of each word is capitalized, including the first word.
let UserProfile = "PascalCase";
let ShoppingCart = "class name style";

// 3. snake_case is a naming convention where words are separated by underscores and all letters are lowercase.
let user_name = "snake_case";
let total_price = 49.99;
let is_logged_in = false;

// 4. UPPERCASE is a naming convention where all letters are uppercase, and words are separated by underscores. It is often used for constants.
const MAX_SIZE = 100;
const API_KEY = "abc123";
const DATABASE_URL = "localhost";

// 5. Hungarian Notation is a naming convention where the variable name is prefixed with a lowercase letter indicating its type or purpose.
let strName = "string prefix";
let bActive = true;       // boolean
let nCount = 5;           // number
let arrItems = [];        // array