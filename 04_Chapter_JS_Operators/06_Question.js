console.log(5 != "5");
console.log(5 !== "5"); // != is not equal operator, it will 
// check if the value of 5 is not equal to the value of "5". 
// It will return false because the value of 5 is equal to 
// the value of "5" but the type is different. The type of 5 is 
// number and the type of "5" is string. So, it will return true
//  because the value is not equal but the type is different.
